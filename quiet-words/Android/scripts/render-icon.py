#!/usr/bin/env python3
"""Renders the Android launcher icon (adaptive) and the Home icon from the iOS drawing.

    python3 scripts/render-icon.py   (from quiet-words/Android)

Reuses `render()` of ../iOS/scripts/render-icon.py (same letters, strokes and colors; needs
Pillow and the Mac's SF Pro Rounded): the foreground is the letters and strokes on
transparent, scaled so the 3×3 grid fits the adaptive icon's safe zone; the background is
the teal gradient as a vector drawable. Also the Gold icon (a reward: `ic_launcher_gold`,
shown by the `.LauncherGold` activity alias).
"""
import importlib.util
import pathlib

from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent
RES = HERE.parent / "words-app/src/main/res"
spec = importlib.util.spec_from_file_location("ios_icon", HERE.parent.parent / "iOS/scripts/render-icon.py")
ios = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ios)

DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
# The grid is 72 % of iOS's square; here it takes ~60 dp of the 108 dp layer (safe zone 66 dp).
SCALE = 60 / 0.72 / 108

def write_icon(name, variant):
    top, bottom, ink, stroke, on_stroke = variant
    art = ios.render(None, None, ink, stroke, on_stroke, size=1024)
    for density, factor in DENSITIES.items():
        side = round(108 * factor)
        inner = round(side * SCALE)
        layer = Image.new("RGBA", (side, side), (0, 0, 0, 0))
        layer.paste(art.resize((inner, inner), Image.LANCZOS), ((side - inner) // 2, (side - inner) // 2))
        folder = RES / f"mipmap-{density}"
        folder.mkdir(parents=True, exist_ok=True)
        layer.save(folder / f"{name}_foreground.png")
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / f"drawable/{name}_background.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/render-icon.py -->
<shape xmlns:android="http://schemas.android.com/apk/res/android">
    <gradient android:angle="270" android:startColor="{top}" android:endColor="{bottom}" />
</shape>
""")
    (RES / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
    (RES / f"mipmap-anydpi-v26/{name}.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/render-icon.py -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/{name}_background" />
    <foreground android:drawable="@mipmap/{name}_foreground" />
</adaptive-icon>
""")


write_icon("ic_launcher", ios.VARIANTS["light"])
write_icon("ic_launcher_gold", ios.GOLD["light"])
(RES / "drawable-nodpi").mkdir(parents=True, exist_ok=True)
ios.render(*ios.VARIANTS["light"], size=256).save(RES / "drawable-nodpi/home_icon.png")
print("Icons written to", RES)
